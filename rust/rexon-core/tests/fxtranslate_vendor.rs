//! Сторож вендорного движка перевода: ядро умножения выбирается ПО
//! ПРОЦЕССОРУ, а не прибивается на сборке.
//!
//! Зачем отдельный файл. `fxtranslate` 0.4.2 жёстко пишет `-mavx2` в своём
//! `build.rs`, и проверки CPUID в крейте нет нигде. Собранный так движок на
//! x86-64 без AVX2 (Intel до Haswell, AMD до Zen, младшие Celeron/Pentium/
//! Atom) даёт SIGILL — причём не на старте: замер стенда показал «загрузка
//! модели: 0.031 с» и код возврата 132 = 128 + 4 на ПЕРВОМ умножении
//! матриц. Для товара это худший вид отказа: программа показала окно и
//! рухнула на первом переводе описания.
//!
//! Лечение — наш патч вендора (`rust/vendor/fxtranslate/patches/`): шим
//! компилируется четыре раза (avx2, avxvnni, avx512bw, avx512vnni) и набор
//! выбирается ОДИН раз при первом обращении по `is_x86_feature_detected!`.
//! Включает многоарочную сборку переменная `FXT_GEMM_X86_MULTI=1` из
//! `rust/.cargo/config.toml`, и вот её-то забыть проще всего: одноарочная
//! сборка выглядит и работает нормально — ровно до чужого процессора.
//!
//! ⭐ Сторож ловит именно это. `FXT_GEMM_FORCE_SCALAR=1` понимает ТОЛЬКО наш
//! диспетчер; в одноарочной сборке набор прибит на сборке и переменную
//! читать некому. Значит «ядро сменилось на скалярное» — доказательство,
//! что диспетчер в двоичном файле есть, и доказательство машинно-независимое:
//! оно не требует ни AVX-512, ни вообще AVX2.
//!
//! ⚠️ Каждая проверка — ДОЧЕРНИМ процессом, и это не перестраховка: выбор
//! набора кеширует `OnceLock`, то есть в одном процессе он происходит один
//! раз навсегда, и второй вариант окружения в нём уже не проверить.

/// Признак дочернего прогона (он же — запрет запускать тело вручную).
const РЕБЁНОК: &str = "REXON_FX_ЯДРО_РЕБЁНОК";

/// Как дочерний прогон сообщает имя выбранного ядра.
const МЕТКА: &str = "ЯДРО=";

/// Каталог с моделью Firefox en→ru для `#[ignore]`-сверки живого перевода.
/// В дерево модель НЕ кладётся (её место — поставка), поэтому путь задаётся
/// окружением, а по умолчанию берётся стендовый.
///
/// Имя переменной — из ядра: его же читает живой поиск модели
/// ([`rexon_core::translator_engine::pick_model_live`]). Своей копии здесь
/// быть не должно — иначе стенд и товар искали бы модель по разным путям.
const МОДЕЛЬ_ENV: &str = rexon_core::translator_engine::MODEL_DIR_ENV;
fn default_model_dir() -> String {
    let home = std::env::var("HOME").unwrap_or_default();
    format!("{home}/file-verify/mt-bench/models/firefox-enru")
}

/// Спросить у дочернего процесса, какое ядро выбрал диспетчер в заданном
/// окружении.
fn ядро_ребёнком(доп: &[(&str, &str)]) -> String {
    let mut cmd = std::process::Command::new(std::env::current_exe().expect("путь бинаря"));
    cmd.args([
        "--exact",
        "печать_ядра_ребёнком",
        "--ignored",
        "--nocapture",
        "--test-threads=1",
    ])
    .env(РЕБЁНОК, "1");
    // Чтобы прогон не зависел от окружения машины, на которой его запустили.
    cmd.env_remove("FXT_GEMM_X86_ARCH");
    cmd.env_remove("FXT_GEMM_FORCE_SCALAR");
    for (имя, значение) in доп {
        cmd.env(имя, значение);
    }
    let out = cmd.output().expect("дочерний прогон");
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(
        out.status.success(),
        "дочерний прогон не прошёл (окружение {доп:?}):\n{stdout}\n{}",
        String::from_utf8_lossy(&out.stderr)
    );
    // Метка ищется ВНУТРИ строки, а не с её начала: libtest печатает свой
    // «test имя ... » без перевода строки, и вывод сверки садится ему в хвост.
    stdout
        .lines()
        .find_map(|l| l.split_once(МЕТКА).map(|(_, хвост)| хвост))
        .unwrap_or_else(|| panic!("дочерний прогон не назвал ядро:\n{stdout}"))
        .trim()
        .to_string()
}

/// Тело опроса — только в дочернем процессе (см. шапку про `OnceLock`).
#[test]
#[ignore = "запускается дочерним процессом ядро_умножения_выбирается_по_cpuid"]
fn печать_ядра_ребёнком() {
    assert!(std::env::var_os(РЕБЁНОК).is_some(), "только дочерний прогон");
    println!("{МЕТКА}{}", fxtranslate::gemm::backend());
}

/// Набор инструкций выбирается по процессору, и выбор этот — во время
/// работы, а не на сборке.
#[cfg(target_arch = "x86_64")]
#[test]
fn ядро_умножения_выбирается_по_cpuid() {
    // 1. Диспетчер В ДВОИЧНОМ ФАЙЛЕ ЕСТЬ. `FXT_GEMM_FORCE_SCALAR` —
    //    аварийный выход нашего патча (для поддержки, если на машине
    //    покупателя SIMD-путь поведёт себя не так); одноарочной сборке эта
    //    переменная неизвестна, и ядро осталось бы SIMD-ным. Проверка не
    //    требует от процессора ничего, поэтому годится на любой машине.
    let скаляр = ядро_ребёнком(&[("FXT_GEMM_FORCE_SCALAR", "1")]);
    assert!(
        скаляр.contains("scalar"),
        "аварийный скалярный выход не сработал (ядро «{скаляр}»). \
         Похоже, сборка ОДНОАРОЧНАЯ: потерялась переменная FXT_GEMM_X86_MULTI=1 \
         из rust/.cargo/config.toml. На процессоре без нужного набора это SIGILL \
         после загрузки модели — см. rust/vendor/fxtranslate/ATTRIBUTION.md."
    );

    // 2. По умолчанию берётся лучший набор, который умеет ЭТОТ процессор.
    let своё = ядро_ребёнком(&[]);
    let ждём = if is_x86_feature_detected!("avx512vnni")
        && is_x86_feature_detected!("avx512bw")
        && is_x86_feature_detected!("avx512vl")
        && is_x86_feature_detected!("avx512dq")
    {
        "avx512vnni"
    } else if is_x86_feature_detected!("avx512bw")
        && is_x86_feature_detected!("avx512vl")
        && is_x86_feature_detected!("avx512dq")
    {
        "avx512bw"
    } else if is_x86_feature_detected!("avxvnni") && is_x86_feature_detected!("avx2") {
        "avxvnni"
    } else if is_x86_feature_detected!("avx2") {
        "avx2"
    } else {
        // Процессора без AVX2 у нас нет, но путь описан: таблицы не будет и
        // движок уйдёт на скалярное ядро крейта — замедление, не падение.
        "scalar"
    };
    assert!(
        своё.contains(ждём),
        "диспетчер выбрал «{своё}», а по флагам процессора ждали «{ждём}»"
    );

    // 3. Копии ядер РАЗНЫЕ и лежат рядом: принудительный AVX2 обязан дать
    //    именно AVX2, даже когда процессор умеет больше. Это же и проверка,
    //    что `objcopy --localize-hidden` не дал компоновщику слить копии.
    if is_x86_feature_detected!("avx2") {
        let навязанный = ядро_ребёнком(&[("FXT_GEMM_X86_ARCH", "avx2")]);
        assert_eq!(
            навязанный, "avx2",
            "принудительный AVX2 дал «{навязанный}» — копии наборов не изолированы"
        );
        if ждём != "avx2" {
            assert_ne!(
                навязанный, своё,
                "навязанный набор совпал с выбранным сам — похоже, копия в файле одна"
            );
        }
    }
}

/// Живой перевод одной фразы en→ru на СКАЧАННОЙ ВРУЧНУЮ модели Firefox.
///
/// `#[ignore]` намеренно: модели в дереве нет и не будет (43 МБ, её место —
/// поставка, это отдельный шаг). Запуск:
///
/// ```sh
/// cargo test -p rexon-core --release --test fxtranslate_vendor \
///     -- --ignored --nocapture перевод_одной_фразы
/// ```
///
/// Каталог модели — `REXON_TRANSLATE_MODEL_DIR` (по умолчанию стендовый). Нужны
/// `model.enru.intgemm.alphas.bin` и `vocab.enru.spm`; короткий список
/// (`lex.*.bin`) намеренно НЕ используется: он отнимает 0,4 chrF++ и 2,8 МБ
/// поставки, а ускорение на десятках коротких описаний не заметно.
#[test]
#[ignore = "нужна скачанная модель Firefox en→ru (REXON_TRANSLATE_MODEL_DIR), в дерево не кладётся"]
fn перевод_одной_фразы() {
    let корень = std::env::var(МОДЕЛЬ_ENV).unwrap_or_else(|_| default_model_dir());
    let модель = std::path::Path::new(&корень).join("model.enru.intgemm.alphas.bin");
    let словарь = std::path::Path::new(&корень).join("vocab.enru.spm");
    assert!(
        модель.is_file() && словарь.is_file(),
        "модели нет: {} — задайте каталог через {МОДЕЛЬ_ENV}",
        корень
    );

    let движок = fxtranslate::engine::Engine::load_mmapped(&модель, &словарь, &словарь)
        .expect("загрузка модели")
        .with_threads(1);
    let источник = "This global theme brings a warm, muted palette to the whole desktop.";
    let начало = std::time::Instant::now();
    let перевод = движок.translate(источник);
    println!("ядро умножения : {}", fxtranslate::gemm::backend());
    println!("источник       : {источник}");
    println!("перевод ({:.3} с): {перевод}", начало.elapsed().as_secs_f64());

    assert!(!перевод.trim().is_empty(), "перевод пустой");
    assert!(
        перевод.chars().any(|c| ('а'..='я').contains(&c)),
        "в переводе нет русских букв: {перевод}"
    );
    // ⭐ Порча первого слова — тот самый дефект, который лечит наш патч
    // (16,0 % строк FLORES-200 теряли начало первого слова: «ная глобальная
    // тема» вместо «эта глобальная тема»). Первое слово обязано быть целым.
    let первое = перевод.split_whitespace().next().unwrap_or_default();
    assert!(
        первое.chars().count() > 2,
        "первое слово перевода обрублено («{первое}») — похоже, потерялась \
         починка первого токена из патча вендора"
    );
}
