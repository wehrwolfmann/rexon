/// Слова, которые кончаются как глагол 2 л. ед. ч., но им не являются.
/// Короткие («лишь», «тишь») отсекаются ещё и длиной — см. [`forbidden`].
const NOT_VERBS: &[&str] = &["брешь", "плешь", "лишь", "тишь", "глушь"];

/// Строки, которым «ты»-форма прощена осознанно. Пусто — и пусть остаётся
/// пустым: каждая запись здесь означает, что покупателю где-то говорят
/// «ты». Формат — точный текст литерала.
const ALLOWED: &[&str] = &[];

/// Формы на «ты» в ЧУЖОЙ речи, которую Rexon не произносит, а переводит.
///
/// Словарь поправок терминов (`translator.rs`, `TERM_FIXES`) чинит машинный
/// перевод описаний тем: автор темы написал «Unzip it», движок дал «извлеки»
/// — правим на «распакуй». Обращение здесь выбирает автор описания, а не
/// продукт: заменить «ты» на «вы» внутри его фразы значило бы смешать два
/// обращения в одном предложении («распакуйте и положи»). Поэтому в паре
/// «форма движка → форма поправки» обе стороны держат лицо оригинала.
///
/// Прощение узкое: точный литерал (одно слово) и ТОЛЬКО в указанном файле.
/// Та же форма в любом другом исходнике или внутри фразы краснеет, как
/// раньше; запись, которой в файле больше нет, тоже краснеет — список не
/// зарастает мёртвыми исключениями.
const FOREIGN_SPEECH: &[(&str, &str)] = &[
    ("src/translator.rs", "распакуй"),
    ("src/translator.rs", "загрузи"),
    ("src/translator.rs", "скачай"),
];

/// Один найденный случай.
#[derive(Debug)]
struct Hit {
    file: String,
    line: usize,
    word: String,
    literal: String,
}

#[test]
fn тексты_ядра_обращаются_на_вы() {
    let src = Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut files = Vec::new();
    collect_rs(&src, &mut files);
    assert!(files.len() > 50, "исходники ядра не найдены: {}", src.display());

    let mut hits: Vec<Hit> = Vec::new();
    let mut foreign_seen = vec![false; FOREIGN_SPEECH.len()];
    for file in &files {
        let text = std::fs::read_to_string(file).expect("исходник не читается");
        let name = file
            .strip_prefix(src.parent().unwrap())
            .unwrap_or(file)
            .display()
            .to_string();
        for (line, literal) in string_literals(&text) {
            if ALLOWED.contains(&literal.as_str()) {
                continue;
            }
            if let Some(k) = FOREIGN_SPEECH.iter().position(|(f, l)| *f == name && *l == literal) {
                foreign_seen[k] = true;
                continue;
            }
            for word in cyrillic_words(&literal) {
                if forbidden(&word) {
                    hits.push(Hit {
                        file: name.clone(),
                        line,
                        word,
                        literal: short(&literal),
                    });
                }
            }
        }
    }

    let stale: Vec<_> = FOREIGN_SPEECH
        .iter()
        .zip(&foreign_seen)
        .filter(|(_, seen)| !**seen)
        .map(|(entry, _)| entry)
        .collect();
    assert!(stale.is_empty(), "исключения FOREIGN_SPEECH больше не встречаются — убрать: {stale:?}");

    assert!(
        hits.is_empty(),
        "строки ядра говорят покупателю «ты» — продукт обращается на «вы»:\n{}",
        hits.iter()
            .map(|h| format!("  {}:{}: «{}» в {}", h.file, h.line, h.word, h.literal))
            .collect::<Vec<_>>()
            .join("\n")
    );
}

/// Сверка сама себя проверяет: подсунутые формы обязаны ловиться, иначе
/// зелёный цвет выше ничего не значит.
#[test]
fn сторож_ловит_формы_на_ты() {
    for bad in [
        "Нажми кнопку",
        "Если хочешь, открой окно",
        "это твой рабочий стол",
        "ты останешься без сессии",
        "убедись, что демон запущен",
        "не найдёшь — напиши",
    ] {
        assert!(
            cyrillic_words(bad).iter().any(|w| forbidden(w)),
            "сторож не заметил «ты»-форму: {bad}"
        );
    }
    for good in [
        "Нажмите кнопку",
        "это ваш рабочий стол",
        "вы останетесь без сессии",
        "убедитесь, что демон запущен",
        // Слова, похожие на 2 л. ед. ч., но ими не являющиеся.
        "брешь в обороне",
        "эта помощь не нужна",
        "мышь и клавиатура",
        "сброс темы ниже — лишь косметика",
    ] {
        assert!(
            !cyrillic_words(good).iter().any(|w| forbidden(w)),
            "сторож покраснел на нормальной строке: {good}"
        );
    }
}

fn forbidden(word: &str) -> bool {
    if NOT_VERBS.contains(&word) {
        return false;
    }
    if PRONOUNS.contains(&word) || IMPERATIVES.contains(&word) {
        return true;
    }
    // Глагол 2 л. ед. ч.: -ешь/-ёшь/-ишь, в том числе возвратный. Порог
    // длины отсекает частицы и существительные той же концовки («лишь»,
    // «тишь»): короче пяти букв таких глаголов в русском нет — самые
    // короткие «идёшь», «ждёшь», «поёшь».
    let stem = word.strip_suffix("ся").unwrap_or(word);
    ["ешь", "ёшь", "ишь"].iter().any(|e| stem.ends_with(e)) && stem.chars().count() > 4
}

/// Слова из кириллицы (дефис внутри слова сохраняется).
fn cyrillic_words(text: &str) -> Vec<String> {
    text.split(|c: char| !(('а'..='я').contains(&c) || ('А'..='Я').contains(&c) || c == 'ё' || c == 'Ё'))
        .filter(|w| !w.is_empty())
        .map(|w| w.to_lowercase())
        .collect()
}

fn short(literal: &str) -> String {
    let trimmed: String = literal.chars().take(60).collect();
    if literal.chars().count() > 60 {
        format!("«{trimmed}…»")
    } else {
        format!("«{trimmed}»")
    }
}

fn collect_rs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    for entry in rd.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_rs(&path, out);
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
}

/// Строковые литералы исходника: `(номер строки, содержимое)`.
///
/// Разбор ручной, а не регулярным выражением: в ядре есть и сырые строки
/// (`r#"…"#`), и экранированные кавычки, и `'x'` рядом с временами жизни
/// `'a` — регулярное выражение на этом ломается молча, а молчащая сверка
/// хуже отсутствующей.
fn string_literals(text: &str) -> Vec<(usize, String)> {
    let chars: Vec<char> = text.chars().collect();
    let mut out = Vec::new();
    let mut line = 1usize;
    let mut i = 0usize;
    while i < chars.len() {
        let c = chars[i];
        if c == '\n' {
            line += 1;
            i += 1;
            continue;
        }
        // Комментарии.
        if c == '/' && chars.get(i + 1) == Some(&'/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
            continue;
        }
        if c == '/' && chars.get(i + 1) == Some(&'*') {
            let mut depth = 1;
            i += 2;
            while i < chars.len() && depth > 0 {
                if chars[i] == '\n' {
                    line += 1;
                }
                if chars[i] == '/' && chars.get(i + 1) == Some(&'*') {
                    depth += 1;
                    i += 2;
                    continue;
                }
                if chars[i] == '*' && chars.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    i += 2;
                    continue;
                }
                i += 1;
            }
            continue;
        }
        // Сырая строка: r"…" / r#"…"# / br#"…"#.
        if c == 'r' || (c == 'b' && chars.get(i + 1) == Some(&'r')) {
            let mut j = if c == 'b' { i + 2 } else { i + 1 };
            let hashes_start = j;
            while chars.get(j) == Some(&'#') {
                j += 1;
            }
            if chars.get(j) == Some(&'"') {
                let hashes = j - hashes_start;
                let start_line = line;
                let mut buf = String::new();
                j += 1;
                loop {
                    match chars.get(j) {
                        None => break,
                        Some('"')
                            if (1..=hashes).all(|k| chars.get(j + k) == Some(&'#'))
                                && hashes == count_hashes(&chars, j + 1) =>
                        {
                            j += 1 + hashes;
                            break;
                        }
                        Some(&ch) => {
                            if ch == '\n' {
                                line += 1;
                            }
                            buf.push(ch);
                            j += 1;
                        }
                    }
                }
                out.push((start_line, buf));
                i = j;
                continue;
            }
        }
        // Обычная строка.
        if c == '"' {
            let start_line = line;
            let mut buf = String::new();
            i += 1;
            while i < chars.len() && chars[i] != '"' {
                if chars[i] == '\\' {
                    // Перенос строки после `\` в исходнике съедается вместе с
                    // отступом — ровно так же, как это делает компилятор.
                    if chars.get(i + 1) == Some(&'\n') {
                        line += 1;
                        i += 2;
                        while matches!(chars.get(i), Some(' ') | Some('\t')) {
                            i += 1;
                        }
                        continue;
                    }
                    i += 2;
                    buf.push(' ');
                    continue;
                }
                if chars[i] == '\n' {
                    line += 1;
                }
                buf.push(chars[i]);
                i += 1;
            }
            i += 1;
            out.push((start_line, buf));
            continue;
        }
        // Символ или время жизни.
        if c == '\'' {
            if chars.get(i + 1) == Some(&'\\') {
                i += 2;
                while i < chars.len() && chars[i] != '\'' {
                    i += 1;
                }
                i += 1;
            } else if chars.get(i + 2) == Some(&'\'') {
                i += 3;
            } else {
                i += 1;
            }
            continue;
        }
        i += 1;
    }
    out
}

fn count_hashes(chars: &[char], from: usize) -> usize {
    let mut n = 0;
    while chars.get(from + n) == Some(&'#') {
        n += 1;
    }
    n
}
