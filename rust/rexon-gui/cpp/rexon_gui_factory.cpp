QByteArray rexon_variant_to_json(const QVariant& value)
{
    // Warning: QML puts into a QVariant property not a ready map but a QJSValue
    // wrapper — the engine unwraps it only on demand. Without this step
    // QJsonDocument::fromVariant would return null for any object coming from
    // QML, that is, map properties would arrive empty.
    const QVariant unwrapped = value.metaType() == QMetaType::fromType<QJSValue>()
        ? value.value<QJSValue>().toVariant()
        : value;
    // Warning: and a second layer: the map may contain Qt Protobuf gadgets
    // (sorting and filter rules). For QJsonDocument a gadget is an unknown type
    // and gives null, and the setting would go to the daemon empty. They are
    // unwrapped by the meta-reflection of the gadget shim — one for the
    // project.
    return QJsonDocument::fromVariant(rexon_plain_variant(unwrapped))
        .toJson(QJsonDocument::Compact);
}

