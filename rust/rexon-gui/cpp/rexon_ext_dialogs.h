// Диалоги QML-процесса: выбор файла, вопрос «да/нет», выбор шрифта, открытие
// каталога в файловом менеджере и страницы в браузере.
//
// ⚠️ Шим диалогов в проекте ОДИН — как и гаджетный шим (см. build.rs). Начался
// он вкладкой «Расширения» (отсюда исторический префикс `rexon_ext_`), а
// пользуются им и «Настройки»: выбор файла темы Windows и выбор системного
// шрифта. Второй такой же файл рядом означал бы вторую копию вложенного цикла
// событий и второй набор граблей с `parentWindow` (правило #12).
//
// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ШИМ, А НЕ ПРЯМОЙ ПОРТ QFileDialog.
//
// На Python эти три вызова были однострочниками из QtWidgets:
// `QFileDialog.getOpenFileName`, `QMessageBox.question`,
// `QDesktopServices.openUrl`. В QML-процессе так нельзя ни одним из них:
//
//   1. QFileDialog и QMessageBox — ВИДЖЕТЫ. Им нужен `QApplication`, а
//      Rust-хозяин окна поднимает `QGuiApplication` (виджетов в процессе нет
//      вовсе — это и есть смысл ухода с PySide6). Создание QWidget без
//      QApplication роняет процесс, а не рисует окно.
//   2. Штатная замена в QML — `QtQuick.Dialogs.FileDialog` и `MessageDialog`.
//      Они АСИНХРОННЫЕ: `open()` возвращает управление сразу, ответ приходит
//      сигналом `accepted`/`rejected`. Публичного C++-класса у них нет —
//      только QML-тип.
//   3. А страница ждёт СИНХРОННЫЙ ответ: `const path = actions.installDialog()`
//      и `if (!actions.confirm(...)) return;`. Переписать её на колбэки
//      значило бы развести два потока управления — один для Python-хозяина,
//      другой для Rust-хозяина, — то есть завести в странице ровно ту вторую
//      копию правил, которая расходится молча (правило #12).
//
// Отсюда решение: диалог создаётся из QML-текста через `QQmlComponent`, а
// ожидание ответа делает ВЛОЖЕННЫЙ `QEventLoop` — ровно то, что делает
// `QDialog::exec()` у виджетов. Снаружи вызов синхронный, внутри — честный
// асинхронный QML-диалог, который на Wayland уходит в портал рабочего стола и
// выглядит родным. Приём в дереве не новый: тем же вложенным циклом ждёт
// ответа демона транспорт вкладки обоев (`rexon_we_socket.cpp`).
//
// Своего QML-файла у диалогов нет намеренно: три десятка строк разметки,
// которые никто не открывает глазами, в статическом ресурсе модуля были бы
// лишним поводом разъехаться со своим единственным вызовом.
#pragma once

#include <cstdint>

#include <QtCore/QString>

// ── выбор файла ───────────────────────────────────────────────────────────

/// Окно выбора одного файла. Возвращает ЛОКАЛЬНЫЙ путь либо пустую строку,
/// если человек передумал (или диалог не поднялся).
///
/// `filter` — фильтр в записи Qt Widgets («Имя (*.ext);;Другое (*)»): тот же
/// текст, что показывала виджетная вкладка, приходит из ядра. Разбор на
/// список `nameFilters` — здесь, чтобы у ядра не появилось второй записи.
QString rexon_ext_pick_file(const QString& title, const QString& filter,
                            const QString& folder);

// ── сохранение файла ──────────────────────────────────────────────────────

/// Окно сохранения файла с подставленным путём `path` (каталог и имя).
/// Возвращает ЛОКАЛЬНЫЙ путь либо пустую строку, если человек передумал
/// (или диалог не поднялся). `filter` — как у `rexon_ext_pick_file`.
QString rexon_ext_save_file(const QString& title, const QString& filter,
                            const QString& path);

// ── вопрос «да/нет» ───────────────────────────────────────────────────────

/// Подтверждение необратимого действия. `true` — человек ответил «Да».
///
/// Отказ поднять диалог — это `false`: молчаливое «да» удалило бы расширение
/// без спроса (правило #13 — защита от дурака).
/// `skin` — цвета скина и подписи кнопок, через U+001F: фон, карточка, текст,
/// акцент, рамка, «Да», «Нет» (`extensions_actions::confirm_skin`).
bool rexon_ext_confirm(const QString& title, const QString& text, const QString& skin);

// ── каталог в файловом менеджере ──────────────────────────────────────────

/// `QDesktopServices::openUrl(QUrl::fromLocalFile(path))`. В QtGui, виджеты не
/// нужны; биндинга в cxx-qt-lib 0.9 нет.
bool rexon_ext_open_folder(const QString& path);

// ── выбор шрифта ──────────────────────────────────────────────────────────

/// Окно выбора шрифта. Возвращает выбранный шрифт строкой «Семейство,кегль» —
/// той самой записью, которую разбирает ядро (`qt_settings::parse_font_spec`,
/// ветка KDE). Своего разбора у шима поэтому нет вовсе.
///
/// `family`/`size` — что показать выбранным при открытии (пустое семейство —
/// «шрифт не задан», кегль `0` — «в настройке его не было»).
///
/// `outcome` — ЧТО ИМЕННО случилось, и без него не обойтись: «человек
/// передумал» и «окно не поднялось» дают одинаково пустую строку, а сказать
/// человеку надо разное (правило #13):
///   *  1 — шрифт выбран (строка непустая);
///   *  0 — человек закрыл окно, не выбрав;
///   * -1 — окно не поднялось вовсе (QML не скомпилировался, нет движка).
QString rexon_ext_pick_font(const QString& title, const QString& family,
                            std::int32_t size, std::int32_t& outcome);

// ── страница товара в браузере ────────────────────────────────────────────

/// `QDesktopServices::openUrl(QUrl(url))` — адрес САЙТА, а не локальный путь.
/// Пустой либо бессхемный адрес — `false`: молчаливая кнопка читается как
/// поломка, и вкладка обязана узнать об отказе.
bool rexon_ext_open_url(const QString& url);
