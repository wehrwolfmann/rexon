    fn keep_key(k: &str) -> bool {
        !k.ends_with("Text") && k != "groupLabel" && !KEYS_0_6_0.contains(&k)
    }

    pub fn strip_message_maps(value: &Value) -> Value {
        if let Value::Object(map) = value {
            if let Some(Value::Array(options)) = map.get("options") {
                let mut out = serde_json::Map::new();
                for (k, v) in map {
                    if k == "options" {
                        out.insert(
                            "values".into(),
                            Value::Array(
                                options
                                    .iter()
                                    .map(|o| o.get("label").cloned().unwrap_or(Value::Null))
                                    .collect(),
                            ),
                        );
                        continue;
                    }
                    out.insert(k.clone(), strip_message_maps(v));
                }
                out.retain(|k, _| keep_key(k));
                return Value::Object(out);
            }
        }
        match value {
            Value::Array(items) => Value::Array(items.iter().map(strip_message_maps).collect()),
            Value::Object(map) => Value::Object(
                map.iter()
                    .filter(|(k, _)| keep_key(k))
                    .map(|(k, v)| (k.clone(), strip_message_maps(v)))
                    .collect(),
            ),
            other => other.clone(),
        }
    }

    /// What the `PluginMessage` maps in the source descriptions lack.
    ///
    /// An empty list means everything is in place. Without this half of the
    /// comparison the first one (`strip_message_maps`) would silently forgive a
    /// COMPLETE loss of the new fields: it strips them, after all.
    ///
    /// Returns a list rather than panicking, because there are two callers:
    /// `cargo test` turns it into an `assert!`, the bench into verdict lines.
    pub fn message_map_problems(sources: &Value) -> Vec<String> {
        let mut problems = Vec::new();
        let mut seen = 0usize;
        for source in sources.as_array().into_iter().flatten() {
            let Some(map) = source.as_object() else { continue };
            for key in ["displayNameText", "remoteHintText"] {
                match map.get(key) {
                    None => problems.push(format!("у источника нет карты {key}")),
                    Some(message) => {
                        if message.get("pluginId").is_none() || message.get("msgid").is_none() {
                            problems
                                .push(format!("карта {key} без обязательных ключей: {message}"));
                        }
                        seen += 1;
                    }
                }
            }
            for sort in map.get("sorts").into_iter().flat_map(|v| v.as_array()).flatten() {
                if sort.get("labelText").is_none() {
                    problems.push("у сортировки нет карты labelText".to_string());
                }
                seen += 1;
            }
            // waywallen 0.3.8: a filter option got a label and its translatable
            // pair. The folding half of the comparison
            // (`strip_message_maps`) looks only at `label`, so the loss
            // of `value`/`labelText` is caught here.
            for filter in map.get("filters").into_iter().flat_map(|v| v.as_array()).flatten() {
                for option in filter
                    .get("options")
                    .into_iter()
                    .flat_map(|v| v.as_array())
                    .flatten()
                {
                    if option.get("value").is_none()
                        || option.get("label").is_none()
                        || option.get("labelText").is_none()
                    {
                        problems.push(format!(
                            "вариант фильтра без value/label/labelText: {option}"
                        ));
                    }
                    seen += 1;
                }
            }
            // ⭐ The status line value is a label for the user, so it is
            // translated; the machine key must stay next to it in `valueText`.
            // Without this check a translation of `value` would be
            // indistinguishable from losing the key by which the "Sources" page
            // translates.
            for status in map.get("status").into_iter().flat_map(|v| v.as_array()).flatten() {
                if status.get("valueText").is_none() {
                    problems.push(format!(
                        "у строки состояния нет ключа valueText: {status}"
                    ));
                }
                seen += 1;
            }
        }
        // The case "the daemon answered with an error" brings no sources at all —
        // there is nothing to demand maps from.
        let empty = sources.as_array().is_none_or(|items| items.is_empty());
        if !empty && seen == 0 {
            problems.push("источники есть, а карт подписей нет вовсе".to_string());
        }
        problems
    }

