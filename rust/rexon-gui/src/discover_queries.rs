/// How many issued cursors to remember (as in the original).
const MAX_SEEN_CURSORS: usize = 128;

/// Error text "the source issued the same cursor" — a Rexon catalogue key.
pub const REPEATED_CURSOR: &str = "The source returned a repeated continuation token.";

/// What exactly the page asked for — the token remembers it instead of the
/// `_done` closure.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct PendingPage {
    page: u32,
    append: bool,
}

/// State of the search query.
#[derive(Debug)]
pub struct SearchState {
    pub base: QueryState,
    pub source_id: String,
    pub query: String,
    /// waywallen 0.6.1: author whose works are listed (ArtistPage).
    pub artist_id: String,
    pub sort_key: String,
    pub tags: Vec<String>,
    /// v0.2.6: the page hides the results while the source requires a login.
    pub browsing_enabled: bool,
    /// QueryList (qextra): the index of the last loaded page minus one.
    pub offset: i32,
    /// The results are exhausted.
    pub no_more: bool,
    /// Error text of the source ITSELF (not of the transport) — shown as a
    /// banner. Since waywallen 0.6.0 a source error is an ordinary query error
    /// (`errorText()` = `error()`); the field stayed for the golden file of
    /// earlier years.
    pub error_text: String,
    /// waywallen 0.6.0: tags that must not be in the results.
    pub excluded_tags: Vec<String>,
    /// waywallen 0.6.0: the matching mode of the chosen values per filter.
    pub filter_match_modes: BTreeMap<String, String>,
    /// Cursor of the next page (sources with `REMOTE_PAGINATION_CURSOR`).
    pub next_cursor: String,
    /// Already issued cursors: a repeat is a source error, not eternal loading.
    seen_cursors: Vec<String>,
    /// The last failure was while loading more — "Retry" loads more rather than
    /// reloading the results.
    failed_append: bool,
    /// The search conditions changed, and the reload waits for the debounce:
    /// loading more of the old results does not go out before it.
    reload_pending: bool,
    pending: BTreeMap<i64, PendingPage>,
}

impl Default for SearchState {
    fn default() -> Self {
        SearchState {
            base: QueryState::default(),
            source_id: String::new(),
            query: String::new(),
            artist_id: String::new(),
            sort_key: String::new(),
            tags: Vec::new(),
            browsing_enabled: true,
            offset: 0,
            no_more: false,
            error_text: String::new(),
            excluded_tags: Vec::new(),
            filter_match_modes: BTreeMap::new(),
            next_cursor: String::new(),
            seen_cursors: Vec::new(),
            failed_append: false,
            reload_pending: false,
            pending: BTreeMap::new(),
        }
    }
}

impl SearchState {
    fn set_text(
        slot: &mut String,
        value: &str,
        signal: &'static str,
    ) -> Vec<Cmd> {
        if slot == value {
            return Vec::new();
        }
        *slot = value.to_string();
        vec![Cmd::Signal(Event::Prop(signal)), Cmd::RequestReload]
    }

    /// The original's `invalidateSearch` (without signals): the previous results
    /// are no longer continued — until the reload, loading more does not go
    /// out.
    fn invalidate(&mut self) {
        self.reload_pending = true;
        self.failed_append = false;
        self.next_cursor.clear();
        self.seen_cursors.clear();
    }

    pub fn set_excluded_tags(&mut self, value: Vec<String>) -> Vec<Cmd> {
        if self.excluded_tags == value {
            return Vec::new();
        }
        self.excluded_tags = value;
        self.invalidate();
        vec![Cmd::Signal(Event::Prop("excludedTagsChanged")), Cmd::RequestReload]
    }

    pub fn set_filter_match_modes(&mut self, value: BTreeMap<String, String>) -> Vec<Cmd> {
        if self.filter_match_modes == value {
            return Vec::new();
        }
        self.filter_match_modes = value;
        self.invalidate();
        vec![Cmd::Signal(Event::Prop("filterMatchModesChanged")), Cmd::RequestReload]
    }

    /// "Retry" (waywallen 0.6.0): only after an error; if loading more failed,
    /// we load more, otherwise we reload the results.
    pub fn retry(&mut self, connected: bool) -> Vec<Cmd> {
        if self.base.status != STATUS_ERROR {
            return Vec::new();
        }
        if self.failed_append {
            self.load_more(connected)
        } else {
            self.reload(connected)
        }
    }

    pub fn set_source_id(&mut self, value: &str) -> Vec<Cmd> {
        let out = Self::set_text(&mut self.source_id, value, "sourceIdChanged");
        if !out.is_empty() {
            self.invalidate();
        }
        out
    }

    pub fn set_query(&mut self, value: &str) -> Vec<Cmd> {
        let out = Self::set_text(&mut self.query, value, "queryChanged");
        if !out.is_empty() {
            self.invalidate();
        }
        out
    }

    /// Same as upstream: a new author invalidates the listing.
    pub fn set_artist_id(&mut self, value: &str) -> Vec<Cmd> {
        let out = Self::set_text(&mut self.artist_id, value, "artistIdChanged");
        if !out.is_empty() {
            self.invalidate();
        }
        out
    }

    pub fn set_sort_key(&mut self, value: &str) -> Vec<Cmd> {
        let out = Self::set_text(&mut self.sort_key, value, "sortKeyChanged");
        if !out.is_empty() {
            self.invalidate();
        }
        out
    }

    pub fn set_tags(&mut self, value: Vec<String>) -> Vec<Cmd> {
        if self.tags == value {
            return Vec::new();
        }
        self.tags = value;
        self.invalidate();
        vec![Cmd::Signal(Event::Prop("tagsChanged")), Cmd::RequestReload]
    }

    pub fn set_browsing_enabled(&mut self, value: bool) -> Vec<Cmd> {
        if self.browsing_enabled == value {
            return Vec::new();
        }
        self.browsing_enabled = value;
        let mut out = vec![Cmd::Signal(Event::Prop("browsingEnabledChanged"))];
        if value {
            self.invalidate();
            out.push(Cmd::RequestReload);
        } else {
            out.extend(self.clear_results());
        }
        out
    }

    /// A port of `clearResults`: no pages, no loading more, the results are
    /// empty.
    pub fn clear_results(&mut self) -> Vec<Cmd> {
        self.offset = 0;
        self.no_more = true;
        self.error_text.clear();
        self.reload_pending = false;
        self.failed_append = false;
        self.next_cursor.clear();
        self.seen_cursors.clear();
        vec![
            Cmd::Model(ModelCmd::Reset {
                rows: Vec::new(),
                has_more: false,
            }),
            Cmd::Signal(Event::Prop("stateChanged")),
        ]
    }

    pub fn reload(&mut self, connected: bool) -> Vec<Cmd> {
        if !self.browsing_enabled {
            return Vec::new();
        }
        self.offset = 0;
        self.no_more = false;
        self.next_cursor.clear();
        self.seen_cursors.clear();
        self.fetch_page(1, false, connected, true)
    }

    pub fn load_more(&mut self, connected: bool) -> Vec<Cmd> {
        if !self.browsing_enabled
            || self.reload_pending
            || self.no_more
            || self.base.status == we_query::STATUS_QUERYING
        {
            return Vec::new();
        }
        let page = (self.offset + 2) as u32;
        self.fetch_page(page, true, connected, true)
    }

    /// Loading more by the model protocol.
    ///
    /// `from_model = true` means we are INSIDE the model's own `reqFetchMore`
    /// handler. Then the model must not be touched: it is already busy with
    /// itself (in Rust this would be a second `&mut` to a live object), and
    /// `setHasMore(false)` there is a no-op anyway — the model reset the flag a
    /// line above, before emitting the signal. The observable sequence does not
    /// change because of this, since an empty flag set gives no signal.
    pub fn fetch_more(&mut self, connected: bool, from_model: bool) -> Vec<Cmd> {
        // waywallen 0.6.0: and not during a request — otherwise the second page
        // would go out with the same cursor.
        if !self.browsing_enabled
            || self.reload_pending
            || self.no_more
            || self.base.status == we_query::STATUS_QUERYING
        {
            return Vec::new();
        }
        let page = (self.offset + 2) as u32;
        self.fetch_page(page, true, connected, !from_model)
    }

    fn fetch_page(
        &mut self,
        page: u32,
        append: bool,
        connected: bool,
        touch_model: bool,
    ) -> Vec<Cmd> {
        let mut out = Vec::new();
        self.reload_pending = false;
        // Original: t->setHasMore(false) BEFORE the request — otherwise GridView
        // pokes fetchMore again while the page is in flight.
        if touch_model {
            out.push(Cmd::Model(ModelCmd::SetHasMore(false)));
        }
        // waywallen 0.6.0: the previous error is removed before a new request, and
        // WHAT exactly may fail now is remembered.
        self.failed_append = append;
        if connected {
            let cleared = we_query::set_error(&mut self.base, "");
            if !cleared.is_empty() {
                out.extend(base_events(cleared));
                out.push(Cmd::Signal(Event::Prop("stateChanged")));
            }
        }
        let (send, signals) = we_query::begin_call(&mut self.base, connected);
        out.extend(base_events(signals));
        if !send {
            return out;
        }
        let token = next_token();
        self.pending.insert(token, PendingPage { page, append });
        // Our filter labels are Russian — the source gets its own tags.
        let required_tags = localizer()
            .lock()
            .expect("переводчик не отравлен")
            .untranslate_tags(&self.tags, &self.source_id);
        out.push(Cmd::Signal(Event::Sent {
            token,
            field: "remote_search",
            request: Request::Search {
                source_id: self.source_id.clone(),
                query: self.query.clone(),
                sort_key: self.sort_key.clone(),
                page,
                required_tags,
                excluded_tags: localizer()
                    .lock()
                    .expect("переводчик не отравлен")
                    .untranslate_tags(&self.excluded_tags, &self.source_id),
                filter_match_modes: self.filter_match_modes.clone(),
                cursor: if append { self.next_cursor.clone() } else { String::new() },
                artist_id: self.artist_id.clone(),
            },
        }));
        out
    }

    pub fn apply(&mut self, token: i64, frame: &[u8]) -> Vec<Cmd> {
        let Some(pending) = self.pending.remove(&token) else {
            return Vec::new();
        };
        let (answer, mut out) = match take_response(&mut self.base, frame) {
            Ok(pair) => pair,
            Err(_) => return decode_failed(&mut self.base),
        };
        let Some(rsp) = answer else {
            return out;
        };
        let sr = match rsp.payload {
            Some(pb::response::Payload::RemoteSearch(sr)) => sr,
            _ => pb::RemoteSearchResponse::default(),
        };
        // waywallen 0.6.0: a source error is a query error (status Error, the text
        // is `errorText`), the results stay as before, and "Retry" repeats exactly
        // the failed step.
        if !sr.error.is_empty() {
            out.extend(self.fail(&sr.error));
            return out;
        }
        // A cursor the source has already issued — a closed loop.
        if sr.has_more
            && !sr.next_cursor.is_empty()
            && self.seen_cursors.contains(&sr.next_cursor)
        {
            out.extend(self.fail(&rexon_core::i18n::tr(REPEATED_CURSOR)));
            return out;
        }
        let rows: Vec<RemoteRow> = sr
            .items
            .iter()
            .map(|it| {
                let mut row = row_from_item(it);
                crate::remote_list_model::acquisition::merge(&mut row);
                row
            })
            .collect();
        // The daemon sometimes promises the next page without sending a single
        // row — without a cursor the infinite scroll would loop on empty requests.
        // With a cursor an empty page is legitimate (0.6.0).
        let more = sr.has_more && (!rows.is_empty() || !sr.next_cursor.is_empty());
        self.next_cursor = sr.next_cursor.clone();
        if !sr.next_cursor.is_empty() {
            if self.seen_cursors.len() == MAX_SEEN_CURSORS {
                self.seen_cursors.remove(0);
            }
            self.seen_cursors.push(sr.next_cursor);
        }
        self.failed_append = false;
        out.extend(self.apply_page(rows, more, sr.error, pending.page, pending.append));
        out.extend(finish(&mut self.base));
        out
    }

    /// Error of a result step: the text and status Error, the results are not
    /// touched.
    fn fail(&mut self, text: &str) -> Vec<Cmd> {
        let mut out = we_query::set_error(&mut self.base, text);
        out.extend(we_query::set_status(&mut self.base, STATUS_ERROR));
        let mut out = base_events(out);
        // `errorText` = the query error, and it is notified by `stateChanged`.
        out.push(Cmd::Signal(Event::Prop("stateChanged")));
        out
    }

    fn apply_page(
        &mut self,
        rows: Vec<RemoteRow>,
        more: bool,
        error: String,
        page: u32,
        append: bool,
    ) -> Vec<Cmd> {
        self.offset = page as i32 - 1;
        self.no_more = !more;
        self.error_text = error;
        vec![
            Cmd::Model(if append {
                ModelCmd::Append {
                    rows,
                    has_more: more,
                }
            } else {
                ModelCmd::Reset {
                    rows,
                    has_more: more,
                }
            }),
            Cmd::Signal(Event::Prop("stateChanged")),
        ]
    }
}

/// The protocol's `RemoteItem` → a row of the result model.
fn row_from_item(it: &pb::RemoteItem) -> RemoteRow {
    RemoteRow {
        item_id: it.id.clone(),
        source_id: it.source_id.clone(),
        title: it.title.clone(),
        preview_url: it.preview_url.clone(),
        author: it.author.clone(),
        wp_type: it.wp_type.clone(),
        // v0.2.6: a boolean downloaded → the acquisition state (3 — present).
        acquisition_state: if it.downloaded { 3 } else { 0 },
        // waywallen 0.5.0: the author's avatar is sent by the source itself
        // (`RemoteItem.author_avatar_url`, `remote_query.cpp`); empty means the
        // panel hides the avatar.
        author_avatar_url: it.author_avatar_url.clone(),
        // OUR CHANGE: the author's works page exists only for the Steam Workshop;
        // the daemon's sources do not know it. Empty hides the button.
        author_url: String::new(),
        // waywallen 0.6.0: the resource size, if the source knows it.
        width: it.width.unwrap_or(0),
        height: it.height.unwrap_or(0),
        // waywallen 0.6.1: image headers and card badges from the source.
        preview_headers: headers_value(&it.preview_headers),
        author_avatar_headers: headers_value(&it.author_avatar_headers),
        badges: Value::Array(
            it.badges
                .iter()
                .map(|b| {
                    let mut m = Map::new();
                    m.insert("id".into(), Value::String(b.id.clone()));
                    m.insert("text".into(), Value::String(b.text.clone()));
                    Value::Object(m)
                })
                .collect(),
        ),
        ..RemoteRow::default()
    }
}

/// `resourceHeadersFromPb` of waywallen 0.6.1: protobuf map -> plain object.
fn headers_value<'a>(headers: impl IntoIterator<Item = (&'a String, &'a String)>) -> Value {
    Value::Object(
        headers
            .into_iter()
            .map(|(k, v)| (k.clone(), Value::String(v.clone())))
            .collect(),
    )
}

