/// The part identical for all four: the properties of the `Query` base,
/// broadcasting its signals and the shared transport switch.
///
/// This is exactly the replacement of Qt inheritance promised by the plan:
/// the macro emits what the original got from the shared base class.
macro_rules! impl_query_base {
    ($query:ident, $state:ident) => {
        impl qobject::$query {
            fn status(&self) -> i32 {
                self.$state.base.status
            }

            fn error(&self) -> QString {
                QString::from(&self.$state.base.error)
            }

            fn querying(&self) -> bool {
                self.$state.base.status == we_query::STATUS_QUERYING
            }

            fn forward_error(&self) -> bool {
                self.$state.base.forward_error
            }

            fn set_forward_error(mut self: Pin<&mut Self>, value: bool) {
                let cmds = set_forward_error_pure(
                    &mut self.as_mut().rust_mut().$state.base,
                    value,
                );
                self.run(&cmds);
            }

            fn set_transport_connected(&self, value: bool) {
                set_connected(value);
            }

            /// Broadcast the base's signals. The values are taken LIVE (from the
            /// state), not as remembered at planning: the `onStatusChanged` handler in
            /// QML reads `status`/`error` and must see the new values.
            fn emit_signal(mut self: Pin<&mut Self>, event: &Event) -> bool {
                match event {
                    Event::Status(value) => {
                        self.as_mut().status_changed(*value);
                    }
                    Event::Querying => self.as_mut().querying_changed(),
                    Event::ErrorChanged => self.as_mut().error_changed(),
                    Event::ForwardErrorChanged => self.as_mut().forward_error_changed(),
                    Event::Finished => self.as_mut().finished(),
                    Event::ErrorOccurred(text) => {
                        self.as_mut().error_occurred(QString::from(text));
                    }
                    Event::AppError(text) => {
                        self.as_mut().app_error_occurred(QString::from(text));
                    }
                    Event::Sent {
                        token,
                        field,
                        request,
                    } => {
                        let bytes = request.encode(*token as u64);
                        // The token's owner is remembered BEFORE the frame goes out: by it the shim
                        // will return the answer to exactly this query, not to "whoever asked for
                        // such a field".
                        let owner = self_ptr(self.as_mut());
                        unsafe { we_transport::remember(*token, owner.cast()) };
                        self.as_mut().send_request(
                            *token,
                            QString::from(*field),
                            QByteArray::from(&bytes[..]),
                        );
                        // Warning: the callback must return WITHOUT delivering the answer: we are
                        // now inside a &mut on this same object, and re-entering through
                        // deliverResponse would take a second mutable reference. The Python seam
                        // only puts the frame into the socket.
                        we_transport::send(*token, field, &bytes);
                    }
                    // Not a base signal — the caller parses it.
                    _ => return false,
                }
                true
            }
        }
    };
}

