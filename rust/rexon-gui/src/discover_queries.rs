/// Numbering lock for the crate's reconciliation tests. The counter is one
/// per process, and the Discover and "Wallpapers" page golden tests both
/// reset it and expect frames from one: running in parallel, they snatched
/// numbers from each other, and one of the comparisons occasionally failed
/// with "nobody to hand answer 2 to".
#[cfg(test)]
pub(crate) fn token_test_lock() -> std::sync::MutexGuard<'static, ()> {
    static LOCK: Mutex<()> = Mutex::new(());
    // A failed comparison must not bring down its neighbour with a "poisoned"
    // lock.
    LOCK.lock().unwrap_or_else(|e| e.into_inner())
}

