// Queries of the Discover page of the Wallpaper Engine tab, ported from
// Python to Rust/cxx-qt: source availability, search with paged results,
// item details, downloading and removal.
//
// The reference is rexon/qt_wallpaper_engine/qml_ui/bridge.py:873
// (RemoteAvailabilityQuery), :936 (RemoteSearchQuery), :1206
// (RemoteDetailsQuery), :1334 (RemoteDownloadQuery). We do NOT touch the
// vendored QML (page/DiscoverPage.qml, page/RemoteDetailPanel.qml), so the
// names of types, properties, signals and invokables match character for
// character.
//
// ── Three things that determine the structure of this file ─────────────────
//
// 1. There is no inheritance. cxx-qt cannot make a Rust QObject inherit
//    from a Rust QObject, while in the original all queries inherit one
//    `Query` base (qextra::QAsyncResult). The base is ported as STATE:
//    `QueryState` from rexon-core::we_query is embedded as a field in every
//    query, and the identical properties/signals are generated by the
//    `impl_query_base!` macro — Qt inheritance is replaced by composition
//    plus code generation, as written in the plan.
//
// 2. The transport is still Python. `client.py` (QWebSocket) moves only in
//    batch 7, so the query does NOT send the frame itself: it assembles the
//    ready `Request` bytes and hands them out with the
//    `sendRequest(token, field, bytes)` signal, and gets the answer through
//    the `deliverResponse(token, frame)` invokable. The token is our own
//    number; by it the query remembers which page it asked for and which
//    item it was downloading (in Python the `_done` closures did that).
//    Robustness: there is no access to a dead object here at all — the
//    delivery is done by the caller, not by a callback through a stored
//    pointer.
//
// 3. The debounce is real. Changing `sourceId`/`query`/`sortKey`/`tags`
//    does not send a request at once: as in the original (qextra
//    query.cpp:16), a single-shot 100 ms timer is armed, and consecutive
//    edits are merged into ONE first-page request. The timer is a C++ shim
//    (cxx-qt-lib has no QTimer wrapper), see cpp/rexon_gui_factory.cpp.
//
// ── What this batch DELIBERATELY does not include ──────────────────────────
//
// The Steam Workshop branches (`_open_workshop`, `_fetch_page_workshop`,
// `_reload_workshop`, `_fetch_authors`, `_watch_workshop_download`) stay in
// Python: they go to Steam with synchronous networking from a background
// thread, and by the plan the Workshop is batch 6. Here the daemon path is
// implemented; the `workshop_serves()` branching is done outside by the
// owning shim, as now.
//
// Warning: this branching is currently TURNED OFF
// (`WORKSHOP_SERVED_LOCALLY = False` in the shim): the Workshop catalogue is
// again served by the daemon plugin, as at the vendor — Wehrwolfmann's
// decision to "follow upstream closely". There is no reason to port those
// branches until the decision is revisited.
//
// The layer split is the same as in batch 2: all state and all decisions
// about "which signal and in what order" live in plain structs without Qt
// (that is what the golden test checks against the LIVE Python queries),
// while the QObject only executes the resulting list of commands.

/// cxx-qt bridge: four query objects of the Discover page.
///
/// All four are in ONE bridge on purpose: the "one bridge per file" rule is
/// about the file, not about the number of QObjects, and they share one
/// base. A side effect of several `#[qobject]`s in a bridge is that the
/// `Self` shortcut stops working in signatures, so the full type name is
/// written everywhere.
#[cxx_qt::bridge]
