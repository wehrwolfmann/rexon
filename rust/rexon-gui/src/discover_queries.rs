/// Rust state of the search query.
#[derive(Default)]
pub struct RemoteSearchQueryRust {
    state: SearchState,
    /// The result model: Qt owns it (the model is a child of the query).
    model: *mut qobject::QObject,
    debounce: *mut qobject::QObject,
    /// The "the model asks for a page → the query asks for it" connection. The
    /// guard must live as long as the query does: its Drop breaks the
    /// connection.
    fetch_guard: Option<cxx_qt::QMetaObjectConnectionGuard>,
}

impl_query_base!(RemoteSearchQuery, state);

/// The reload debounce interval (qextra query.cpp:16).
const DEBOUNCE_MS: i32 = 100;

/// A pointer to the owner for the closure of the "model → query"
/// connection.
///
/// cxx-qt requires a signal handler to be `Send` (one entry point serves
/// queued connections too), and a raw pointer is not. Our connection is
/// DIRECT and within the family: the model is a child of the query, they
/// live in one thread, and the handler is executed by the same thread as
/// the `emit`. The wrapper is written explicitly so that this statement
/// stands in the code rather than being implied.
struct OwnerPtr(*mut qobject::RemoteSearchQuery);

// SAFETY: the pointer does not cross thread boundaries — see above.
unsafe impl Send for OwnerPtr {}

/// A pointer to the object itself as a QObject — the factory gets the
/// parent with it.
fn self_ptr<T>(object: Pin<&mut T>) -> *mut qobject::QObject {
    let raw: *mut T = unsafe { object.get_unchecked_mut() };
    raw.cast()
}

impl cxx_qt::Initialize for qobject::RemoteSearchQuery {
    fn initialize(mut self: Pin<&mut Self>) {
        let owner = self_ptr(self.as_mut());
        // The model is created in post-construction, not lazily in the getter: QML
        // reads the property on the very first binding, and the getter is const.
        let model = unsafe { qobject::rexon_new_search_result_model(owner) };
        let timer = unsafe { qobject::rexon_new_reload_debounce(owner, DEBOUNCE_MS) };
        {
            let mut rust = self.as_mut().rust_mut();
            rust.model = model;
            rust.debounce = timer;
        }

        // qextra try_connect_fetch_more: the model asks for the next page. The
        // pointer to the owner in the closure is safe precisely because the model
        // is its child: it will not outlive the query by a single tick.
        let query = OwnerPtr(unsafe { self.as_mut().get_unchecked_mut() });
        let model_ptr = model.cast::<crate::remote_list_model::qobject::RemoteListModel>();
        let guard = unsafe { Pin::new_unchecked(&mut *model_ptr) }.on_req_fetch_more(
            move |_model, _row| {
                // Capturing the WHOLE wrapper, not the field: in the 2021 edition a closure
                // takes `query.0` separately — that is, a bare pointer that is not Send,
                // and the connection would not compile.
                let owner = &query;
                // Warning: we are INSIDE the model's signal handler, that is, the model is
                // busy with itself right now. from_model=true forbids touching it.
                let query = unsafe { Pin::new_unchecked(&mut *owner.0) };
                query.fetch_more_internal(true);
            },
        );
        self.as_mut().rust_mut().fetch_guard = Some(guard);
    }
}

