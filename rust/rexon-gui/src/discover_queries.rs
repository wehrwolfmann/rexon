/// The source the "Workshop" page opens on.
///
/// We take what the daemon offered — as at the vendor. Previously we
/// substituted the Steam Workshop here, because we served the catalogue
/// ourselves and no login was required; now the catalogue is the vendor's
/// again, and we have no default value of our own (see
/// `WORKSHOP_SERVED_LOCALLY` in the shim).
///
/// `sources` are those already selected by the tab's boundaries. If the
/// daemon offers a catalogue that is not in the tab (Wallhaven), there is no
/// default value at all: the page then takes the first source of the list
/// itself.
pub fn pick_default(sources: &[Value], daemon_default: &str) -> String {
    let present = sources
        .iter()
        .any(|s| s.get("id").and_then(Value::as_str) == Some(daemon_default));
    if present {
        daemon_default.to_string()
    } else {
        String::new()
    }
}

/// State of the availability query.
#[derive(Debug, Default)]
pub struct AvailabilityState {
    pub base: QueryState,
    pub sources: Vec<Value>,
    pub default_source_id: String,
    pending: BTreeMap<i64, ()>,
}

impl AvailabilityState {
    pub fn reload(&mut self, connected: bool) -> Vec<Cmd> {
        let (send, signals) = we_query::begin_call(&mut self.base, connected);
        let mut out = base_events(signals);
        if !send {
            return out;
        }
        let token = next_token();
        self.pending.insert(token, ());
        out.push(Cmd::Signal(Event::Sent {
            token,
            field: "remote_availability",
            request: Request::Availability,
        }));
        out
    }

    pub fn apply(&mut self, token: i64, frame: &[u8]) -> Vec<Cmd> {
        if self.pending.remove(&token).is_none() {
            // The answer is not ours (or already handled) — silently dropped, as the
            // client did for a dead owner.
            return Vec::new();
        }
        let (answer, mut out) = match take_response(&mut self.base, frame) {
            Ok(pair) => pair,
            Err(_) => return decode_failed(&mut self.base),
        };
        let Some(rsp) = answer else {
            return out;
        };
        let av = match rsp.payload {
            Some(pb::response::Payload::RemoteAvailability(av)) => av,
            _ => pb::RemoteAvailabilityResponse::default(),
        };
        let mut l10n = localizer().lock().expect("переводчик не отравлен");
        // Boundaries of the WE tab: only catalogues from the owners' whitelist (the
        // Steam Workshop of the OWE plugin). Wallhaven, Sketchfab and any future
        // upstream catalogue do not get here; Wallhaven lives in "Appearance → HD
        // Wallpapers". The list is `we_query::WE_TAB_REMOTE_OWNERS`.
        self.sources = av
            .sources
            .iter()
            .filter(|s| we_query::we_tab_shows_remote_owner(&s.owner_plugin_id))
            .map(|s| {
                let info = source_info(s);
                l10n.translate_source(&info).unwrap_or(info)
            })
            .collect();
        drop(l10n);
        self.default_source_id = pick_default(&self.sources, &av.default_source_id);
        out.push(Cmd::Signal(Event::Prop("sourcesChanged")));
        out.extend(finish(&mut self.base));
        out
    }
}

/// A broken frame: the daemon may be newer than us, and crashing in the
/// middle of reception is not allowed — the query goes into Error with an
/// understandable text (in Python this is the `except` branch in
/// `_core_call`).
fn decode_failed(state: &mut QueryState) -> Vec<Cmd> {
    let mut out = we_query::set_error(state, &rexon_core::i18n::tr("could not parse the daemon response"));
    out.extend(we_query::set_status(state, STATUS_ERROR));
    base_events(out)
}

