/// A request frame to the daemon in parsed form — that is how the golden
/// file compares it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Request {
    Availability,
    Search {
        source_id: String,
        query: String,
        sort_key: String,
        page: u32,
        required_tags: Vec<String>,
        /// waywallen 0.6.0: excluded tags, the per-filter matching mode
        /// ("any"/"all") and the continuation cursor (only when loading more).
        excluded_tags: Vec<String>,
        filter_match_modes: BTreeMap<String, String>,
        cursor: String,
        /// waywallen 0.6.1: limit the search to one author.
        artist_id: String,
    },
    Details {
        source_id: String,
        id: String,
    },
    Download {
        source_id: String,
        id: String,
    },
    Uninstall {
        source_id: String,
        id: String,
    },
}

impl Request {
    /// The `oneof payload` field this request goes into.
    pub fn field(&self) -> &'static str {
        match self {
            Request::Availability => "remote_availability",
            Request::Search { .. } => "remote_search",
            Request::Details { .. } => "remote_details",
            Request::Download { .. } => "remote_download",
            Request::Uninstall { .. } => "remote_uninstall",
        }
    }

    /// The ready bytes of the protocol `Request`. `request_id` is left zero: it
    /// is issued by the transport, which has its own counter (`RequestIds`).
    /// The bytes of the `Request` frame with the number already set.
    ///
    /// The number comes as a parameter rather than zero: previously the Python
    /// client substituted it, parsing and reassembling the ready frame. Now the
    /// number is one and is set in the same place where the frame is assembled.
    pub fn encode(&self, request_id: u64) -> Vec<u8> {
        let rid = request_id;
        match self {
            Request::Availability => we_client::remote_availability(rid),
            Request::Search {
                source_id,
                query,
                sort_key,
                page,
                required_tags,
                excluded_tags,
                filter_match_modes,
                cursor,
                artist_id,
            } => we_client::remote_search(
                rid,
                &we_client::RemoteSearch {
                    query,
                    sort_key,
                    page: *page,
                    source_id,
                    tags: required_tags,
                    excluded_tags,
                    filter_match_modes,
                    cursor,
                    artist_id,
                },
            ),
            Request::Details { source_id, id } => we_client::remote_details(rid, id, source_id),
            Request::Download { source_id, id } => we_client::remote_download(rid, id, source_id),
            Request::Uninstall { source_id, id } => we_client::remote_uninstall(rid, id, source_id),
        }
    }

    /// The frame fields in the same form the golden file prints them (names
    /// from protobuf, including default values).
    pub fn to_json(&self) -> Value {
        let mut map = Map::new();
        match self {
            Request::Availability => {}
            Request::Search {
                source_id,
                query,
                sort_key,
                page,
                required_tags,
                excluded_tags,
                filter_match_modes,
                cursor,
                artist_id,
            } => {
                // waywallen 0.6.1: printed only when set, like the 0.6.0 fields.
                if !artist_id.is_empty() {
                    map.insert("artist_id".into(), Value::String(artist_id.clone()));
                }
                // The 0.6.0 fields are printed only when set: the golden file was captured
                // before them, and with empty ones the frame form is the same as before.
                if !excluded_tags.is_empty() {
                    map.insert(
                        "excluded_tags".into(),
                        Value::Array(excluded_tags.iter().cloned().map(Value::String).collect()),
                    );
                }
                if !filter_match_modes.is_empty() {
                    map.insert(
                        "filter_match_modes".into(),
                        Value::Object(
                            filter_match_modes
                                .iter()
                                .map(|(k, v)| (k.clone(), Value::String(v.clone())))
                                .collect(),
                        ),
                    );
                }
                if !cursor.is_empty() {
                    map.insert("cursor".into(), Value::String(cursor.clone()));
                }
                map.insert("source_id".into(), Value::String(source_id.clone()));
                map.insert("query".into(), Value::String(query.clone()));
                map.insert("sort_key".into(), Value::String(sort_key.clone()));
                map.insert("page".into(), Value::from(*page));
                map.insert(
                    "required_tags".into(),
                    Value::Array(
                        required_tags
                            .iter()
                            .map(|t| Value::String(t.clone()))
                            .collect(),
                    ),
                );
            }
            Request::Details { source_id, id }
            | Request::Download { source_id, id }
            | Request::Uninstall { source_id, id } => {
                map.insert("source_id".into(), Value::String(source_id.clone()));
                map.insert("id".into(), Value::String(id.clone()));
            }
        }
        Value::Object(map)
    }

    /// Parsing a frame assembled by `encode()` — the bench uses it to compare
    /// the bytes that actually left with the signal, not just the intention to
    /// send them.
    pub fn decode(bytes: &[u8]) -> Option<Request> {
        let request = pb::Request::decode(bytes).ok()?;
        Some(match request.payload? {
            pb::request::Payload::RemoteAvailability(_) => Request::Availability,
            pb::request::Payload::RemoteSearch(s) => Request::Search {
                source_id: s.source_id,
                query: s.query,
                sort_key: s.sort_key,
                page: s.page,
                required_tags: s.required_tags,
                excluded_tags: s.excluded_tags,
                filter_match_modes: s.filter_match_modes.into_iter().collect(),
                cursor: s.cursor,
                artist_id: s.artist_id,
            },
            pb::request::Payload::RemoteDetails(d) => Request::Details {
                source_id: d.source_id,
                id: d.id,
            },
            pb::request::Payload::RemoteDownload(d) => Request::Download {
                source_id: d.source_id,
                id: d.id,
            },
            pb::request::Payload::RemoteUninstall(u) => Request::Uninstall {
                source_id: u.source_id,
                id: u.id,
            },
            _ => return None,
        })
    }
}

/// Signals of the Query base → observable events.
fn base_events(signals: Vec<QuerySignal>) -> Vec<Cmd> {
    signals
        .into_iter()
        .map(|s| {
            Cmd::Signal(match s {
                QuerySignal::StatusChanged(v) => Event::Status(v),
                QuerySignal::QueryingChanged => Event::Querying,
                QuerySignal::ErrorChanged => Event::ErrorChanged,
                QuerySignal::ForwardErrorChanged => Event::ForwardErrorChanged,
                QuerySignal::Finished => Event::Finished,
                QuerySignal::ErrorOccurred(e) => Event::ErrorOccurred(e),
                QuerySignal::AppErrorOccurred(e) => Event::AppError(e),
                // Properties of the core's simple queries do not come here: parsing the
                // Discover answers lives here and sends Event::Prop itself.
                QuerySignal::Property(name) => Event::Prop(name),
            })
        })
        .collect()
}

/// Take the `Response` off a raw frame and handle a non-OK status.
///
/// A copy of `we_query::take_response`, which is declared `pub(crate)` in the
/// core. Duplicated deliberately: parsing the Discover answers lives in the
/// GUI crate by the plan (batch 3), and extending the core's surface for one
/// function would mean touching someone else's zone.
fn take_response(
    state: &mut QueryState,
    frame_bytes: &[u8],
) -> Result<(Option<pb::Response>, Vec<Cmd>), prost::DecodeError> {
    let frame = pb::ServerFrame::decode(frame_bytes)?;
    let Some(pb::server_frame::Kind::Response(rsp)) = frame.kind else {
        return Err(prost::DecodeError::new("кадр сервера без ответа"));
    };
    if rsp.status != pb::Status::Ok as i32 {
        let text = we_query::response_error_text(rsp.status, &rsp.message);
        let mut out = we_query::set_error(state, &text);
        out.extend(we_query::set_status(state, STATUS_ERROR));
        return Ok((None, base_events(out)));
    }
    Ok((Some(rsp), Vec::new()))
}

/// The shared tail of successful parsing: the properties are updated — the
/// status goes to Finished.
fn finish(state: &mut QueryState) -> Vec<Cmd> {
    base_events(we_query::set_status(state, STATUS_FINISHED))
}

/// The base's `setForwardError` — the same for all four queries.
fn set_forward_error_pure(state: &mut QueryState, value: bool) -> Vec<Cmd> {
    base_events(we_query::set_forward_error(state, value))
}

